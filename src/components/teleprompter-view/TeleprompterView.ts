import css from './teleprompter-view.css?inline'
import html from './teleprompter-view.html?raw'
import { TeleprompterState, type TeleprompterEvent } from '../../domain/TeleprompterState'
import type { SpeechReport } from '../../domain/SpeechReport'

const sheet = new CSSStyleSheet()
sheet.replaceSync(css)

const template = document.createElement('template')
template.innerHTML = html

const COUNTDOWN_SECONDS = 3

/**
 * Represents a teleprompter view.
 */
export class TeleprompterView extends HTMLElement {
  #textArea: HTMLElement
  #viewport: HTMLElement
  #countdownMessage: HTMLElement
  #teleprompter: HTMLElement
  #teleprompterState = new TeleprompterState()
  #controlButtons: HTMLButtonElement[]
  #openTeleprompterButton: HTMLButtonElement
  #speakingSeconds = 0
  #animation: Animation | null = null
  #countdownTimer: number | undefined

  /**
   * Creates an instance of the current type.
   */
  constructor() {
    super()
    const shadowRoot = this.attachShadow({ mode: 'open' })
    shadowRoot.adoptedStyleSheets = [sheet]
    shadowRoot.appendChild(template.content.cloneNode(true))

    this.#textArea = shadowRoot.querySelector('#speech') as HTMLElement
    this.#viewport = shadowRoot.querySelector('#viewport') as HTMLElement
    this.#countdownMessage = shadowRoot.querySelector('.countdown') as HTMLElement
    this.#teleprompter = shadowRoot.querySelector('#teleprompter') as HTMLElement
    this.#controlButtons = [...shadowRoot.querySelectorAll('button[data-event]')] as HTMLButtonElement[]
    this.#openTeleprompterButton = shadowRoot.querySelector('#open') as HTMLButtonElement

    for (const button of this.#controlButtons) {
      button.addEventListener('click', () => this.#send(button.dataset.event as TeleprompterEvent))
    }

    this.#openTeleprompterButton.addEventListener('click', () => this.#open())
  }

  /**
   * Loads the speech to play. Updates the text, timing and word count,
   * then re-checks which controls are enabled.
   *
   * @param speech - The speech text.
   * @param report - The analysis of that speech.
   */
  load(speech: string, report: SpeechReport): void {
    this.#textArea.textContent = speech
    this.#speakingSeconds = report.speakingSeconds
    this.#teleprompterState.wordCount = report.wordCount
    this.#refreshButtons()
  }

  /**
   * Opens the teleprompter section,
   * and updates button state.
   */
  #open(): void {
    this.#teleprompter.hidden = false
    this.#openTeleprompterButton.hidden = true
    this.#refreshButtons()
  }

  /**
   * Closes the teleprompter section,
   * and updates button state.
   */
  #close(): void {
    this.#teleprompter.hidden = true
    this.#openTeleprompterButton.hidden = false
    this.#refreshButtons()
  }

  /**
   * Updates the screen to match the event that was just sent.
   *
   * @param event - The event the state machine accepted.
   */
  #show(event: TeleprompterEvent): void {
    switch (event) {
      case 'start':
      case 'restart':
        this.#reset()
        this.#countdownMessage.hidden = false
        this.#countdownTimer = window.setTimeout(() => {
          this.#countdownMessage.hidden = true
          this.#send('countdownEnded')
        }, COUNTDOWN_SECONDS * 1000)
        break
      case 'countdownEnded':
        this.#animation = this.#scrollSpeech()
        break
      case 'resume':
        this.#animation?.play()
        break
      case 'pause':
        this.#animation?.pause()
        break
      case 'exit':
        this.#reset()
        this.#close()
        break
    }
  }

  /**
   * Scrolls the speech upwards over the speaking time.
   * Sends speechEnded when the speech has scrolled to the end.
   * Generated by Claude Opus 5.5 High.
   *
   * @returns The running animation, so it can be paused, resumed and cancelled.
   */
  #scrollSpeech(): Animation {
    const distance = this.#textArea.scrollHeight - this.#viewport.clientHeight
    const animation = this.#textArea.animate(
      [{ transform: 'translateY(0)' }, { transform: `translateY(-${distance}px)` }],
      { duration: this.#speakingSeconds * 1000, easing: 'linear', fill: 'forwards' }
    )
    animation.addEventListener('finish', () => this.#send('speechEnded'))
    return animation
  }

  /**
   * Stops the countdown timer and the scrolling,
   * and moves the speech back to the top.
   */
  #reset(): void {
    window.clearTimeout(this.#countdownTimer)
    this.#countdownMessage.hidden = true
    this.#animation?.cancel()
  }

  /**
   * Used to send event to the state machine.
   *
   * @param event The event that should be sent.
   */
  #send(event: TeleprompterEvent): void {
    if (!this.#teleprompterState.canSend(event)) {
      return
    }
    this.#teleprompterState.send(event)
    this.#show(event)
    this.#refreshButtons()
  }

  /**
   * Enables only the buttons whose event the current state accepts.
   */
  #refreshButtons(): void {
    for (const button of this.#controlButtons) {
      button.disabled = !this.#teleprompterState.canSend(button.dataset.event as TeleprompterEvent)
    }
  }
}

customElements.define('teleprompter-view', TeleprompterView)
